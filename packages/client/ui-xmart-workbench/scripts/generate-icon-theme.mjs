/**
 * Bake Material Icon Theme associations + referenced SVGs into
 * src/client/icon-theme-data.ts so the browser bundle stays self-contained
 * (the plugin server only serves client.js).
 */
import { generateManifest } from 'material-icon-theme'
import { createRequire } from 'module'
import { basename, dirname, join } from 'path'
import { fileURLToPath } from 'url'
import { readFileSync, writeFileSync } from 'fs'

const require = createRequire(import.meta.url)
const pkg = dirname(require.resolve('material-icon-theme/package.json'))
const here = dirname(fileURLToPath(import.meta.url))
const dest = join(here, '..', 'src', 'client', 'icon-theme-data.ts')

const manifest = generateManifest()
const used = new Set()
const add = (id) => {
  if (typeof id === 'string' && id !== '') used.add(id)
}
add(manifest.file)
add(manifest.folder)
add(manifest.folderExpanded)
for (const table of [
  manifest.fileNames, manifest.fileExtensions,
  manifest.folderNames, manifest.folderNamesExpanded,
]) {
  for (const id of Object.values(table ?? {})) add(id)
}

const svgs = {}
for (const id of used) {
  const def = manifest.iconDefinitions?.[id]
  const iconPath = def?.iconPath
  if (typeof iconPath !== 'string') continue
  const file = join(pkg, 'icons', basename(iconPath))
  let svg
  try {
    svg = readFileSync(file, 'utf8')
  } catch {
    continue
  }
  svgs[id] = minifySvg(svg)
}

const data = {
  file: manifest.file ?? 'file',
  folder: manifest.folder ?? 'folder',
  folderExpanded: manifest.folderExpanded ?? 'folder-open',
  fileNames: manifest.fileNames ?? {},
  fileExtensions: manifest.fileExtensions ?? {},
  folderNames: manifest.folderNames ?? {},
  folderNamesExpanded: manifest.folderNamesExpanded ?? {},
  svgs,
}

const payload = JSON.stringify(JSON.stringify(data))
const source = [
  '/* oxlint-disable -- generated Material Icon Theme tables; do not edit. */',
  '/**',
  ' * Generated by scripts/generate-icon-theme.mjs — do not edit.',
  ' * Associations and SVG markup from material-icon-theme (MIT).',
  ' * Regenerate: pnpm --filter @deepseek-ai/dsh-client-ui-xmart-workbench generate:icons',
  ' */',
  "import type { IconThemeData } from './file-icon.ts'",
  '',
  `export const ICON_THEME: IconThemeData = JSON.parse(${payload})`,
  '',
].join('\n')

writeFileSync(dest, source)
process.stdout.write(`wrote ${dest} (${used.size} ids, ${Object.keys(svgs).length} svgs, ${Buffer.byteLength(source)} bytes)\n`)

function minifySvg(svg) {
  return svg
    .replace(/<\?xml[^?]*\?>/g, '')
    .replace(/<!--[\s\S]*?-->/g, '')
    .replace(/\s+/g, ' ')
    .replace(/> </g, '><')
    .trim()
}
