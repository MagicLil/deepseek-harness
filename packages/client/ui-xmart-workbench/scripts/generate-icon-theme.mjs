/**
 * Bake the VS Code / Seti file-icon associations and SVGs into the browser
 * bundle. The runtime keeps the same data-URI renderer used by the explorer;
 * only the source icon collection changes from Material to Seti.
 */
import { createRequire } from 'module'
import { dirname, join } from 'path'
import { fileURLToPath } from 'url'
import { existsSync, readFileSync, writeFileSync } from 'fs'

const require = createRequire(import.meta.url)
const pkg = dirname(require.resolve('seti-ui/package.json'))
const here = dirname(fileURLToPath(import.meta.url))
const dest = join(here, '..', 'src', 'client', 'icon-theme-data.ts')
const mapping = readFileSync(join(pkg, 'styles', 'components', 'icons', 'mapping.less'), 'utf8')

const fileNames = {}
const fileExtensions = {}
const used = new Set(['default', 'folder'])
for (const match of mapping.matchAll(/\.icon-set\("([^"]+)",\s*"([^"]+)"/gu)) {
  const key = match[1]
  const id = match[2]
  used.add(id)
  const exactFile = join(pkg, 'file-types', key)
  if (existsSync(exactFile) || !key.startsWith('.')) fileNames[key.toLowerCase()] = id
  else fileExtensions[key.slice(1).toLowerCase()] = id
}

const svgs = {}
for (const id of used) {
  try {
    svgs[id] = minifySvg(readFileSync(join(pkg, 'icons', `${id}.svg`), 'utf8'))
  } catch {
    // Some mapping entries are symbolic aliases without a standalone SVG.
  }
}

const data = {
  file: 'default',
  folder: 'folder',
  folderExpanded: 'folder',
  fileNames,
  fileExtensions,
  folderNames: {},
  folderNamesExpanded: {},
  svgs,
}
const payload = JSON.stringify(JSON.stringify(data))
const source = [
  '/* oxlint-disable -- generated Seti Icon Theme tables; do not edit. */',
  '/**',
  ' * Generated by scripts/generate-icon-theme.mjs — do not edit.',
  ' * Associations and SVG markup from seti-ui (MIT).',
  ' * Regenerate: pnpm --filter @deepseek-ai/dsh-client-ui-xmart-workbench generate:icons',
  ' */',
  "import type { IconThemeData } from './file-icon.ts'",
  '',
  `export const ICON_THEME: IconThemeData = JSON.parse(${payload})`,
  '',
].join('\n')
writeFileSync(dest, source)
process.stdout.write(`wrote ${dest} (${used.size} ids, ${Object.keys(svgs).length} svgs, ${Buffer.byteLength(source)} bytes)\n`)

function minifySvg(svg) {
  return svg
    .replace(/<\?xml[^?]*\?>/gu, '')
    .replace(/<!--[\s\S]*?-->/gu, '')
    .replace(/\s+/gu, ' ')
    .replace(/> </gu, '><')
    .trim()
}
